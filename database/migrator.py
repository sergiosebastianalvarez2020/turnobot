"""Migrador SQLite → PostgreSQL (Fase 5A — migrador de datos controlado).

Lee datos de una base SQLite existente, los transforma según el mapeo de tipos
definido en ``migrations_pg/001_initial_schema.sql`` y los inserta en una base
PostgreSQL vacía, preservando IDs y foreign keys.

Características:
    - Preserva IDs existentes (GENERATED BY DEFAULT permite INSERT explícito).
    - No copia índices SQLite (el esquema PostgreSQL ya define los suyos).
    - No copia tablas FTS5 de SQLite (PostgreSQL usa tsvector+GIN, GENERATED).
    - Maneja conversiones: INTEGER, BOOLEAN(0/1→true/false), DATE, TIME,
      TIMESTAMPTZ, TEXT, NULL.
    - Transaccional en PostgreSQL: un error en cualquier tabla hace rollback
      completo de la transacción de inserción.
    - Modo DRY-RUN: valida y reporta sin escribir.
    - Idempotencia: si la BD destino ya contiene datos, se rechaza explícitamente.
    - Ajusta sequences al MAX(id) tras la inserción.
    - Reconstruye document_tsearch (GENERATED STORED) automáticamente al insertar.
"""

from __future__ import annotations

import dataclasses
import datetime
import logging
import sqlite3
import time
from pathlib import Path
from typing import Any

import psycopg

logger = logging.getLogger("turnobot.migrator")

