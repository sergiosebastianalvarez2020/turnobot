def test_unique_constraints_present():
    schema = _read_schema()
    inline_text = [
        ("businesses", "slug"),
        ("roles", "name"),
        ("users", "email"),
        ("platform_users", "email"),
    ]
    for table, col in inline_text:
        assert re.search(
            rf"CREATE TABLE\s+{table}\b[^;]*?\b{col}\s+TEXT NOT NULL UNIQUE\b", schema, re.DOTALL
        ), f"falta UNIQUE en {table}.{col}"
    inline_bigint = [("business_settings", "business_id"), ("loyalty_settings", "business_id")]
    for table, col in inline_bigint:
        assert re.search(
            rf"CREATE TABLE\s+{table}\b[^;]*?\b{col}\s+BIGINT NOT NULL UNIQUE\b", schema, re.DOTALL
        ), f"falta UNIQUE en {table}.{col}"
    composite = [
        ("weekly_schedules", "business_id, day_of_week"),
        ("business_users", "user_id, business_id"),
        ("loyalty_accounts", "business_id, customer_phone"),
        ("rewards", "business_id, name"),
        ("redemptions", "business_id, idempotency_key"),
        ("resources", "business_id, name"),
        ("conversation_sessions", "business_id, customer_phone"),
        ("conversation_analytics", "business_id, question_hash"),
    ]
    for table, cols in composite:
        assert re.search(
            rf"CREATE TABLE\s+{table}\b[^;]*?UNIQUE\s*\(\s*{cols}",
            schema,
            re.DOTALL | re.IGNORECASE,
        ), f"falta UNIQUE({cols}) en {table}"


