def test_postgres_types_mapping():
    schema = _read_schema()
    assert re.search(r"CREATE TABLE\s+services\b.*?price\s+NUMERIC\(10,2\)", schema, re.DOTALL), (
        "services.price debe ser NUMERIC(10,2)"
    )
    assert re.search(
        r"CREATE TABLE\s+appointments\b.*?appointment_date\s+DATE\s+NOT NULL.*?appointment_time\s+TIME\s+NOT NULL",
        schema,
        re.DOTALL,
    ), "appointment_date DATE y appointment_time TIME"
    assert re.search(
        r"CREATE TABLE\s+retention_actions\b.*?last_completed_date\s+DATE\b", schema, re.DOTALL
    ), "retention_actions.last_completed_date debe ser DATE"
    assert re.search(
        r"CREATE TABLE\s+weekly_schedules\b.*?morning_start\s+TIME\b", schema, re.DOTALL
    ), "horarios semanales deben ser TIME"
    assert re.search(r"\bTIMESTAMPTZ\b", schema), "usa timestamps TIMESTAMPTZ"
    for flag in (
        "active",
        "revoked",
        "notifications_enabled",
        "is_open",
        "needs_human",
        "pending",
        "enabled",
    ):
        assert re.search(rf"\b{flag}\s+BOOLEAN\b", schema), f"{flag} debe ser BOOLEAN"


def test_no_fts5_artifacts():
    schema = _code_only(_read_schema())
    assert re.search(r"CREATE TABLE\s+business_knowledge\b", schema), (
        "business_knowledge debe existir"
    )
    assert "business_knowledge_fts" not in schema, "FTS queda fuera de la Fase 4E"
    assert not re.search(r"\bfts5\b", schema, re.IGNORECASE), "no debe haber FTS5"
    assert not re.search(r"CREATE VIRTUAL TABLE", schema, re.IGNORECASE), "no tablas virtuales"
    assert not re.search(r"CREATE TRIGGER", schema, re.IGNORECASE), "no triggers"
    assert "bk_fts" not in schema, "no triggers de sincronizacion FTS"


def test_no_sqlite_only_syntax():
    schema = _code_only(_read_schema())
    assert "AUTOINCREMENT" not in schema.upper(), "AUTOINCREMENT no es de PostgreSQL"
    assert not re.search(r"\bPRAGMA\b", schema, re.IGNORECASE), "PRAGMA no es de PostgreSQL"
    assert not re.search(r"\bINSERT\s+OR\b", schema, re.IGNORECASE), (
        "INSERT OR IGNORE/REPLACE no aplica"
    )
    assert not re.search(r"\bBEGIN IMMEDIATE\b", schema, re.IGNORECASE), "BEGIN IMMEDIATE no aplica"
    assert "datetime(" not in schema.lower(), "datetime('now') no es de PostgreSQL"
    assert "ALTER TABLE" not in schema.upper(), "esquema final: sin migraciones ADD COLUMN"


